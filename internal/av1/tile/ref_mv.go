func (c *BlockModeContext) scanGridBlockReferenceMV(req ReferenceMVStackRequest, rowOffset int, colOffset int, matches *int, newMatches *int, stack *ReferenceMVStack) {
	x := req.X4 + colOffset
	y := req.Y4 + rowOffset
	candidate, size, ok := c.gridInterMotion(x, y)
	if !ok {
		// Fall back to the cross-SB snapshots when the lookup crosses the
		// current superblock's boundary. libaom's frame-level mi grid covers
		// these neighbors via xd->mi[row_offset*stride + col_offset]; goav1
		// stages the prior-SB cells in SBTop* / SBLeft* / SBDiagonal* at SB
		// store time, gated by per-snapshot Valid bits.
		//
		// The case-by-case fallback handles:
		//   - y<0, x<0 (top-left diagonal cell) via SBDiagonal: needed for
		//     monochrome frame 3 mi=(16,64) where the SB(3,0) bottom-right
		//     corner cell at (15,63) hosts an inter LAST block contributing
		//     RowMatches=1; without the fallback ctx=51 (refCtx=3) instead of
		//     libaom's 67 (refCtx=4).
		//   - y<0, x>=0 (strictly-above cell within the current SB column)
		//     via SBTop: needed for cdf_update frame 1 mi=(64,2) where the
		//     outer (-1,-1) scan reads the SB-above bottom row to find a
		//     duplicate of the LEFT candidate's MV and bump its weight, which
		//     flips the post-sort NEAR slot from stack[1]=(7,21) (the LEFT
		//     entry) to stack[1]=(9,-71) (the ABOVE entry). Without the
		//     fallback the decoded NEAR MV is (7,21) instead of (9,-71),
		//     which then propagates into subsequent block decisions and
		//     desyncs the entropy stream starting at the (68,0) seq=228966
		//     newmv/drl divergence.
		//   - x<0, y>=0 (strictly-left cell within the current SB row) via
		//     SBLeft, mirroring the SBTop case for the column dimension.
		//
		// The SB-top fallback must be gated on req.HaveTop AND mi_row >
		// tile_row_start (the cell's mi-row mi_row+y must not cross the tile
		// boundary). libaom's is_inside() applies the same per-direction
		// check.
		if y < 0 && x >= 0 {
			if !req.HaveTop {
				return
			}
			// Tile-row check: mi_row + y must be >= tile_row_start. The
			// SB-top snapshot only carries the prior-SB grid contents, but
			// the candidate at that cell is invalid (across the tile) if the
			// current block sits at the first SB row of its tile.
			if int64(req.MIRow)+int64(y) < int64(req.TileMIRowStart) {
				return
			}
			depth := -y - 1
			if depth < 0 || depth >= intrabcCrossSBHistory ||
				x >= MaxBlockModeSlots ||
				c.SBTopMotionValidGrid[depth][x] == 0 {
				return
			}
			candidate = c.SBTopInterMotionGrid[depth][x]
			size = c.SBTopBlockSizeGrid[depth][x]
		} else if y < 0 {
			// Diagonal up-left cell: served from the SBDiagonal carrier
			// snapshotted from the SB that finished decoding directly
			// up-and-to-the-left of the current SB. Mirrors the intrabc
			// diagonal lookup in crossSBIntrabcGridInterMotion.
			if !req.HaveTop || !req.HaveLeft {
				return
			}
			d := -y - 1
			e := -x - 1
			if d < 0 || d >= intrabcCrossSBHistory ||
				e < 0 || e >= intrabcCrossSBHistory ||
				c.SBDiagonalMotionValidGrid[d][e] == 0 {
				return
			}
			candidate = c.SBDiagonalInterMotionGrid[d][e]
			size = c.SBDiagonalBlockSizeGrid[d][e]
		} else {
			if !req.HaveLeft {
				return
			}
			depth := -x - 1
			if depth < 0 || depth >= intrabcCrossSBHistory ||
				y >= MaxBlockModeSlots ||
				c.SBLeftMotionValidGrid[depth][y] == 0 {
				return
			}
			candidate = c.SBLeftInterMotionGrid[depth][y]
			size = c.SBLeftBlockSizeGrid[depth][y]
		}
	}
	m, n := stack.addDirectCandidate(candidate, size, req.References, 4, req.GlobalMVs, req.GlobalMotionType)
	*matches += m
	*newMatches += n
}

func (c *BlockModeContext) scanGridBlockIntrabcDV(req ReferenceMVStackRequest, rowOffset int, colOffset int, weight uint16, stack *ReferenceMVStack) {
	x := req.X4 + colOffset
	y := req.Y4 + rowOffset
	if y < 0 && x < 0 {
		// Diagonal cell across both SB borders: libaom's mi grid cell at
		// (mi_col-1-e, mi_row-1-d). Recovered via SBDiagonalInterMotionGrid
		// snapshotted from the SB diagonally up-left of the current SB.
		candidate, _, ok := c.crossSBIntrabcGridInterMotion(req, x, y)
		if !ok {
			return
		}
		stack.addOrWeight(ReferenceMVCandidate{This: candidate.MV[0]}, weight)
		return
	}
	if y < 0 {
		// Cross-SB-row lookup: consult the SB-top snapshot of the row
		// directly above the current superblock. This mirrors libaom's
		// frame-level mi grid, which is unaffected by in-SB block decode.
		if !req.HaveTop || x < 0 || x >= MaxBlockModeSlots || c.SBTopMotionValid[x] == 0 {
			return
		}
		stack.addOrWeight(ReferenceMVCandidate{This: c.SBTopInterMotion[x].MV[0]}, weight)
		return
	}
	if x < 0 {
		// Cross-SB-column lookup: consult the SB-left snapshot of the column
		// directly to the left of the current superblock. Same rationale as
		// the SB-top snapshot but for the row dimension.
		if !req.HaveLeft || y < 0 || y >= MaxBlockModeSlots || c.SBLeftMotionValid[y] == 0 {
			return
		}
		stack.addOrWeight(ReferenceMVCandidate{This: c.SBLeftInterMotion[y].MV[0]}, weight)
		return
	}
	candidate, _, ok := c.gridInterMotion(x, y)
	if !ok {
		return
	}
	stack.addOrWeight(ReferenceMVCandidate{This: candidate.MV[0]}, weight)
}

func (c *BlockModeContext) gridInterMotion(x4 int, y4 int) (InterMotionResult, BlockSize, bool) {
	if x4 < 0 || y4 < 0 || x4 >= MaxBlockModeSlots || y4 >= MaxBlockModeSlots ||
		c.GridMotionValid[y4][x4] == 0 {
		return InterMotionResult{}, 0, false
	}
	return c.GridInterMotion[y4][x4], c.GridBlockSize[y4][x4], true
}

// gridNeighborBlockSize returns the block size recorded at (x4, y4)
// regardless of whether the cell carries a usable motion candidate.
// MarkIntra records the intra block's size in GridBlockSize while clearing
// GridMotionValid so outer ref-MV scans can advance by libaom's
// `i += mi_size_*[candidate->bsize]` stride past intra neighbors without
// oversampling cells the candidate already covers. Returns (size, true) when
// a Mark*() recorded a size at the slot, (0, false) when the slot is out of
// range. The "size present" signal is the gridBlockSizeVisited bitmap, which
// flips only when markGridInterMotion / clearGridInterMotion writes the slot.
func (c *BlockModeContext) gridNeighborBlockSize(x4 int, y4 int) (BlockSize, bool) {
	if x4 < 0 || y4 < 0 || x4 >= MaxBlockModeSlots || y4 >= MaxBlockModeSlots {
		return 0, false
	}
	if c.GridBlockSizeVisited[y4][x4] == 0 {
		return 0, false
	}
	return c.GridBlockSize[y4][x4], true
}

// crossSBGridNeighborBlockSize mirrors gridNeighborBlockSize but transparently
// falls back to the SB-top / SB-left / SB-diagonal snapshots when the lookup
// crosses the current superblock boundary. libaom's mi grid is frame-wide so
// scan_row_mbmi / scan_col_mbmi see prior-SB neighbors without ceremony; goav1
// keeps a per-SB grid and stages the prior SB's bottom rows in SBTop*Grid /
// its right columns in SBLeft*Grid (depth 0 = adjacent cell, depth d = d+1
// cells away). Used by the inter ref-MV outer row/column scan so a block at
// the top edge (Y4=0) or left edge (X4=0) of an SB still observes deep outer
// offsets (-3, -5) that would otherwise be clipped at the SB boundary.
func (c *BlockModeContext) crossSBGridNeighborBlockSize(req ReferenceMVStackRequest, x4, y4 int) (BlockSize, bool) {
	if c == nil {
		return 0, false
	}
	if y4 < 0 && x4 < 0 {
		if !req.HaveTop || !req.HaveLeft {
			return 0, false
		}
		d := -y4 - 1
		e := -x4 - 1
		if d < 0 || d >= intrabcCrossSBHistory || e < 0 || e >= intrabcCrossSBHistory {
			return 0, false
		}
		// Use BlockSizeVisited (not MotionValid) so intra neighbors in the
		// prior SB still consume their mi_size when the outer scan steps
		// across them. libaom's scan_row/col_mbmi advances i += len based
		// on the candidate's bsize regardless of whether the candidate is
		// inter or intra; if we gated the lookup on MotionValid here the
		// intra cell looked "unknown" and the scan fell back to a single-
		// mi step, then re-entered cells the intra neighbor already covered
		// and may pick up a stray inter MV one row deeper. mfmv frame 1
		// block mi=(64,18) outer_col[-5] hit this: libaom visits (19,59)
		// (intra bsize=BLOCK_16X8, len=2) and exits with col_match=0, while
		// goav1 stepped to (20,59) (inter, mv=(-4,23)) and inflated
		// col_match to 1.
		if c.SBDiagonalBlockSizeVisitedGrid[d][e] == 0 {
			return 0, false
		}
		return c.SBDiagonalBlockSizeGrid[d][e], true
	}
	if y4 < 0 {
		if !req.HaveTop {
			return 0, false
		}
		depth := -y4 - 1
		if depth < 0 || depth >= intrabcCrossSBHistory ||
			x4 < 0 || x4 >= MaxBlockModeSlots ||
			c.SBTopBlockSizeVisitedGrid[depth][x4] == 0 {
			return 0, false
		}
		return c.SBTopBlockSizeGrid[depth][x4], true
	}
	if x4 < 0 {
		if !req.HaveLeft {
			return 0, false
		}
		depth := -x4 - 1
		if depth < 0 || depth >= intrabcCrossSBHistory ||
			y4 < 0 || y4 >= MaxBlockModeSlots ||
			c.SBLeftBlockSizeVisitedGrid[depth][y4] == 0 {
			return 0, false
		}
		return c.SBLeftBlockSizeGrid[depth][y4], true
	}
	return c.gridNeighborBlockSize(x4, y4)
}

// crossSBInterGridInterMotion mirrors gridInterMotion but consults the SB-top
// / SB-left / SB-diagonal snapshots when the lookup crosses the superblock
// boundary. Symmetric to crossSBIntrabcGridInterMotion but returns the full
// InterMotionResult so the inter ref-MV outer row/column scan can match the
// candidate's reference frame, mode (NEWMV detection), and motion vector
// against the current block's reference list.
func (c *BlockModeContext) crossSBInterGridInterMotion(req ReferenceMVStackRequest, x4, y4 int) (InterMotionResult, BlockSize, bool) {
	return c.crossSBIntrabcGridInterMotion(req, x4, y4)
}

// crossSBIntrabcGridInterMotion returns the InterMotionResult and block size
// at (x4, y4) honoring cross-superblock fallback to the prior SB snapshots for
// the intrabc outer mv-ref scan. When y4 < 0 the row lives in the SB above
// (consult SBTopInterMotionGrid); when x4 < 0 the column lives in the SB to
// the left (SBLeftInterMotionGrid). Both negative is the diagonal cell, only
// recoverable via the top-row snapshot the prior SB column shares with the
// row above. Returns (result, size, false) when no candidate is available.
func (c *BlockModeContext) crossSBIntrabcGridInterMotion(req ReferenceMVStackRequest, x4, y4 int) (InterMotionResult, BlockSize, bool) {
	if c == nil {
		return InterMotionResult{}, 0, false
	}
	if y4 < 0 && x4 < 0 {
		// Diagonal cell at frame position (mi_col-1-e, mi_row-1-d) inside
		// the SB up-and-to-the-left. Recovered from SBDiagonalInterMotionGrid,
		// loaded from the carrier's Diagonal slot for the current root column.
		// Requires both HaveTop and HaveLeft because the diagonal SB shares
		// one row with the above SB and one column with the left SB; without
		// either the (-1,-1) cell falls outside the tile.
		if !req.HaveTop || !req.HaveLeft {
			return InterMotionResult{}, 0, false
		}
		d := -y4 - 1
		e := -x4 - 1
		if d < 0 || d >= intrabcCrossSBHistory || e < 0 || e >= intrabcCrossSBHistory {
			return InterMotionResult{}, 0, false
		}
		if c.SBDiagonalMotionValidGrid[d][e] == 0 {
			return InterMotionResult{}, 0, false
		}
		return c.SBDiagonalInterMotionGrid[d][e], c.SBDiagonalBlockSizeGrid[d][e], true
	}
	if y4 < 0 {
		if !req.HaveTop {
			return InterMotionResult{}, 0, false
		}
		depth := -y4 - 1
		if depth < 0 || depth >= intrabcCrossSBHistory ||
			x4 < 0 || x4 >= MaxBlockModeSlots ||
			c.SBTopMotionValidGrid[depth][x4] == 0 {
			return InterMotionResult{}, 0, false
		}
		return c.SBTopInterMotionGrid[depth][x4], c.SBTopBlockSizeGrid[depth][x4], true
	}
	if x4 < 0 {
		if !req.HaveLeft {
			return InterMotionResult{}, 0, false
		}
		depth := -x4 - 1
		if depth < 0 || depth >= intrabcCrossSBHistory ||
			y4 < 0 || y4 >= MaxBlockModeSlots ||
			c.SBLeftMotionValidGrid[depth][y4] == 0 {
			return InterMotionResult{}, 0, false
		}
		return c.SBLeftInterMotionGrid[depth][y4], c.SBLeftBlockSizeGrid[depth][y4], true
	}
	return c.gridInterMotion(x4, y4)
}

func (c *BlockModeContext) topRightInterMotion(req ReferenceMVStackRequest, dims BlockDimensions) (InterMotionResult, BlockSize, bool) {
	x := req.X4 + int(dims.W4)
	y := req.Y4 - 1
	if y >= 0 {
		candidate, size, ok := c.gridInterMotion(x, y)
		return candidate, size, ok
	}
	if !req.HaveTop || x < 0 {
		return InterMotionResult{}, 0, false
	}
	if x >= MaxBlockModeSlots {
		// Block sits at the current SB's right edge with sbSizeMIB ==
		// MaxBlockModeSlots, so the topright cell at frame
		// mi(mi_row-1, mi_col+W4) lives in the SB-above-and-to-the-right.
		// AboveInterMotion cannot represent slot >= MaxBlockModeSlots, so the
		// SB-above-right snapshot loaded from carrier.Above[rootColIndex+1] at
		// SB load time supplies the cell. Slot indexed by offset within the
		// right SB, i.e. x - MaxBlockModeSlots when sbSizeMIB ==
		// MaxBlockModeSlots. Mirrors libaom xd->mi[-stride + xd->width].
		if !c.SBTopRightValid {
			return InterMotionResult{}, 0, false
		}
		slot := x - MaxBlockModeSlots
		if slot < 0 || slot >= MaxBlockModeSlots {
			return InterMotionResult{}, 0, false
		}
		if c.SBTopRightIntra[slot] != 0 || c.SBTopRightMotionValid[slot] == 0 {
			return InterMotionResult{}, 0, false
		}
		return c.SBTopRightInterMotion[slot], c.SBTopRightBlockSize[slot], true
	}
	if c.AboveIntra[x] != 0 || c.AboveMotionValid[x] == 0 {
		return InterMotionResult{}, 0, false
	}
	return c.AboveInterMotion[x], c.AboveBlockSize[x], true
}

func blockSizeWidth4(size BlockSize) int {
	dims, ok := size.Dimensions()
	if !ok || dims.W4 == 0 {
		return 1
	}
	return int(dims.W4)
}

func blockSizeHeight4(size BlockSize) int {
	dims, ok := size.Dimensions()
	if !ok || dims.H4 == 0 {
		return 1
	}
	return int(dims.H4)
}

func (c *BlockModeContext) extendSingleReferenceMVStack(req ReferenceMVStackRequest, dims BlockDimensions, stack *ReferenceMVStack) {
	if req.HaveTop {
		for off := 0; off < int(dims.W4) && stack.Count < MaxMVRefCandidates; {
			slot := req.X4 + off
			step := c.aboveCandidateStep(slot, int(dims.W4)-off)
			if c.AboveIntra[slot] == 0 && c.AboveMotionValid[slot] != 0 {
				stack.addSingleFallbackCandidate(c.AboveInterMotion[slot], req.References.Ref[0], req.RefSignBias)
			}
			off += step
		}
	}
	if req.HaveLeft {
		for off := 0; off < int(dims.H4) && stack.Count < MaxMVRefCandidates; {
			slot := req.Y4 + off
			step := c.leftCandidateStep(slot, int(dims.H4)-off)
			if c.LeftIntra[slot] == 0 && c.LeftMotionValid[slot] != 0 {
				stack.addSingleFallbackCandidate(c.LeftInterMotion[slot], req.References.Ref[0], req.RefSignBias)
			}
			off += step
		}
	}
	// SingleRefMVs is seeded by BuildReferenceMVStack after the final stack
	// sort so the nearest/near cache reflects libaom's mv_ref_list, which
	// libaom populates from the sorted ref_mv_stack, not the per-helper
	// insertion order.
}

func (c *BlockModeContext) extendCompoundReferenceMVStack(req ReferenceMVStackRequest, dims BlockDimensions, stack *ReferenceMVStack) {
	if stack.Count >= MaxMVRefCandidates {
		return
	}
	var refs compoundReferenceLists
	c.collectCompoundReferenceLists(req, dims, &refs)
	comp := refs.compoundList(req)
	if stack.Count == 1 {
		candidate := ReferenceMVCandidate{This: comp[0][0], Compound: comp[0][1], Weight: 2}
		if stack.Candidates[0].This == candidate.This && stack.Candidates[0].Compound == candidate.Compound {
			candidate = ReferenceMVCandidate{This: comp[1][0], Compound: comp[1][1], Weight: 2}
		}
		stack.Candidates[stack.Count] = candidate
		stack.Count++
		return
	}
	for stack.Count < MaxMVRefCandidates {
		idx := stack.Count
		stack.Candidates[stack.Count] = ReferenceMVCandidate{This: comp[idx][0], Compound: comp[idx][1], Weight: 2}
		stack.Count++
	}
}

func (c *BlockModeContext) collectCompoundReferenceLists(req ReferenceMVStackRequest, dims BlockDimensions, lists *compoundReferenceLists) {
	if req.HaveTop {
		for off := 0; off < int(dims.W4); {
			slot := req.X4 + off
			step := c.aboveCandidateStep(slot, int(dims.W4)-off)
			if c.AboveIntra[slot] == 0 && c.AboveMotionValid[slot] != 0 {
				lists.add(c.AboveInterMotion[slot], req.References.Ref, req.RefSignBias)
			}
			off += step
		}
	}
	if req.HaveLeft {
		for off := 0; off < int(dims.H4); {
			slot := req.Y4 + off
			step := c.leftCandidateStep(slot, int(dims.H4)-off)
			if c.LeftIntra[slot] == 0 && c.LeftMotionValid[slot] != 0 {
				lists.add(c.LeftInterMotion[slot], req.References.Ref, req.RefSignBias)
			}
			off += step
		}
	}
}

func (c *BlockModeContext) aboveCandidateStep(slot int, remaining int) int {
	step := 1
	if c.AboveMotionValid[slot] != 0 {
		if dims, ok := c.AboveBlockSize[slot].Dimensions(); ok && int(dims.W4) > step {
			step = int(dims.W4)
		}
	}
	if step > remaining {
		step = remaining
	}
	return step
}

func (c *BlockModeContext) leftCandidateStep(slot int, remaining int) int {
	step := 1
	if c.LeftMotionValid[slot] != 0 {
		if dims, ok := c.LeftBlockSize[slot].Dimensions(); ok && int(dims.H4) > step {
			step = int(dims.H4)
		}
	}
	if step > remaining {
		step = remaining
	}
	return step
}

func validateReferenceMVStackRequest(req ReferenceMVStackRequest) (BlockDimensions, error) {
	dims, ok := req.Size.Dimensions()
	if !ok {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	if err := validateBlockModeSlot(req.X4, req.Y4); err != nil {
		return BlockDimensions{}, err
	}
	if req.X4+int(dims.W4) > MaxBlockModeSlots || req.Y4+int(dims.H4) > MaxBlockModeSlots {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	if err := validateInterReferences(req.References); err != nil {
		return BlockDimensions{}, err
	}
	if req.TemporalMVSampleUnavailable && !req.UseRefFrameMVS {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	if req.TemporalMVs != nil && !req.UseRefFrameMVS {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	if req.TemporalMVs != nil &&
		(req.TileMIColEnd <= req.TileMIColStart || req.TileMIRowEnd <= req.TileMIRowStart ||
			req.MICol < req.TileMIColStart || req.MICol >= req.TileMIColEnd ||
			req.MIRow < req.TileMIRowStart || req.MIRow >= req.TileMIRowEnd) {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	return dims, nil
}

func validateIntrabcReferenceDVStackRequest(req ReferenceMVStackRequest) (BlockDimensions, error) {
	dims, ok := req.Size.Dimensions()
	if !ok {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	if err := validateBlockModeSlot(req.X4, req.Y4); err != nil {
		return BlockDimensions{}, err
	}
	if req.X4+int(dims.W4) > MaxBlockModeSlots || req.Y4+int(dims.H4) > MaxBlockModeSlots {
		return BlockDimensions{}, ErrInvalidDecodeState
	}
	return dims, nil
}

func validateInterMotion(result InterMotionResult) error {
	if err := validateInterReferences(result.References); err != nil {
		return err
	}
	if result.Mode.Compound != result.References.Compound {
		return ErrInvalidDecodeState
	}
	if result.Mode.Compound {
		if !result.Mode.CompoundMode.Valid() {
			return ErrInvalidDecodeState
		}
		return nil
	}
	if !result.Mode.Mode.Valid() {
		return ErrInvalidDecodeState
	}
	return nil
}

func validateInterReferences(refs InterReferencesResult) error {
	if !refs.Ref[0].Valid() {
		return ErrInvalidDecodeState
	}
	if refs.Compound {
		if !refs.Ref[1].Valid() {
			return ErrInvalidDecodeState
		}
		return nil
	}
	if refs.Ref[1] != ReferenceFrameNone {
		return ErrInvalidDecodeState
	}
	return nil
}

func blockHasTopRight(sbSizeMIB uint8, block BlockVisit) bool {
	dims, ok := block.Size.Dimensions()
	if !ok || sbSizeMIB == 0 {
		return false
	}
	bs := maxInt(int(dims.W4), int(dims.H4))
	if bs <= 0 || bs > blockSizeWidth4(BlockSize64x64) {
		return false
	}
	sbSize := int(sbSizeMIB)
	maskRow := int(block.MIRow) & (sbSize - 1)
	maskCol := int(block.MICol) & (sbSize - 1)
	hasTopRight := !((maskRow&bs) != 0 && (maskCol&bs) != 0)
	for cur := bs; cur < sbSize; cur <<= 1 {
		if (maskCol & cur) == 0 {
			break
		}
		if (maskCol&(2*cur)) != 0 && (maskRow&(2*cur)) != 0 {
			hasTopRight = false
			break
		}
	}
	if dims.W4 < dims.H4 && !blockIsLastVerticalRect(block, dims) {
		hasTopRight = true
	}
	if dims.W4 > dims.H4 && !blockIsFirstHorizontalRect(block) {
		hasTopRight = false
	}
	return hasTopRight
}

func blockIsFirstHorizontalRect(block BlockVisit) bool {
	levelSize := int(block.Level.Size4x4())
	if levelSize <= 0 {
		return true
	}
	return (int(block.MIRow) & (levelSize - 1)) == 0
}

func blockIsLastVerticalRect(block BlockVisit, dims BlockDimensions) bool {
	levelSize := int(block.Level.Size4x4())
	if levelSize <= 0 {
		return true
	}
	return (int(block.MICol)&(levelSize-1))+int(dims.W4) >= levelSize
}

func (stack *ReferenceMVStack) addDirectCandidate(candidate InterMotionResult, candidateSize BlockSize, refs InterReferencesResult, weight uint16, globalMVs [2]motion.Vector, globalTypes [2]parser.GlobalMotionType) (int, int) {
	if refs.Compound {
		if !candidate.References.Compound ||
			candidate.References.Ref[0] != refs.Ref[0] ||
			candidate.References.Ref[1] != refs.Ref[1] {
			return 0, 0
		}
		this := candidate.MV[0]
		comp := candidate.MV[1]
		if isGlobalMVBlock(candidate.Mode, candidateSize, globalTypes[0]) {
			this = globalMVs[0]
		}
		if isGlobalMVBlock(candidate.Mode, candidateSize, globalTypes[1]) {
			comp = globalMVs[1]
		}
		stack.addOrWeight(ReferenceMVCandidate{This: this, Compound: comp}, weight)
		return 1, boolInt(candidate.Mode.usesNewMV())
	}

	matches := 0
	for ref := 0; ref < 2; ref++ {
		if candidate.References.Ref[ref] != refs.Ref[0] {
			continue
		}
		mv := candidate.MV[ref]
		if isGlobalMVBlock(candidate.Mode, candidateSize, globalTypes[0]) {
			mv = globalMVs[0]
		}
		stack.addOrWeight(ReferenceMVCandidate{This: mv}, weight)
		matches++
	}
	if matches == 0 {
		return 0, 0
	}
	return matches, boolInt(candidate.Mode.usesNewMV())
}

// isGlobalMVBlock mirrors libaom's is_global_mv_block(): the candidate is
// treated as a global-motion block when its prediction mode is GLOBALMV or
// GLOBAL_GLOBALMV, the corresponding warp model is non-translational (RotZoom
// or Affine), and the candidate's smaller side is at least 8 luma samples
// (W4 >= 2 and H4 >= 2). libaom substitutes the global MV evaluated at the
// CURRENT decode block's position for such candidates so two neighbors decoded
// with the same affine model still contribute distinct ref-MV stack entries
// when the projection produces different sub-pel values at different positions.
// Without this substitution goav1 reuses the candidate's stored MV — evaluated
// at the candidate's own position — which collapses entries libaom keeps
// separate and undercounts ref_mv_count, e.g. cdf_update frame 1 block (12,4)
// where the left BLOCK_16X16 GLOBALMV neighbor dedups against the above
// BLOCK_16X8 NEARESTMV candidate.
func isGlobalMVBlock(mode InterModeResult, size BlockSize, gmType parser.GlobalMotionType) bool {
	if gmType <= parser.GlobalMotionTranslation {
		return false
	}
	if !isGlobalMode(mode) {
		return false
	}
	dims, ok := size.Dimensions()
	if !ok {
		return false
	}
	if dims.W4 < 2 || dims.H4 < 2 {
		return false
	}
	return true
}

func isGlobalMode(mode InterModeResult) bool {
	if mode.Compound {
		return mode.CompoundMode == CompoundInterModeGlobalGlobal
	}
	return mode.Mode == InterModeGlobalMV
}

func (stack *ReferenceMVStack) addSingleFallbackCandidate(candidate InterMotionResult, target ReferenceFrame, signBias [referenceFrameCount]bool) {
	for ref := 0; ref < 2 && stack.Count < MaxMVRefCandidates; ref++ {
		candidateRef := candidate.References.Ref[ref]
		if !candidateRef.Valid() {
			continue
		}
		mv := candidate.MV[ref]
		if signBias[candidateRef] != signBias[target] {
			mv = negateMV(mv)
		}
		stack.addUniqueFallback(ReferenceMVCandidate{This: mv, Weight: 2})
	}
}

func (stack *ReferenceMVStack) addOrWeight(candidate ReferenceMVCandidate, weight uint16) {
	for i := 0; i < stack.Count; i++ {
		if stack.Candidates[i].This == candidate.This && stack.Candidates[i].Compound == candidate.Compound {
			stack.Candidates[i].Weight += weight
			return
		}
	}
	if stack.Count >= MaxRefMVStackSize {
		return
	}
	candidate.Weight = weight
	stack.Candidates[stack.Count] = candidate
	stack.Count++
}

func (stack *ReferenceMVStack) addUniqueFallback(candidate ReferenceMVCandidate) {
	for i := 0; i < stack.Count; i++ {
		if stack.Candidates[i].This == candidate.This && stack.Candidates[i].Compound == candidate.Compound {
			return
		}
	}
	if stack.Count >= MaxRefMVStackSize {
		return
	}
	stack.Candidates[stack.Count] = candidate
	stack.Count++
}

func (stack *ReferenceMVStack) setSingleRefMVs(globalMV motion.Vector) {
	for i := 0; i < MaxMVRefCandidates; i++ {
		stack.SingleRefMVs[i] = globalMV
	}
	for i := 0; i < MaxMVRefCandidates && i < stack.Count; i++ {
		stack.SingleRefMVs[i] = stack.Candidates[i].This
	}
	stack.SingleRefValid = true
}

func referenceMVModeContext(nearestMatch int, refMatchCount int, newMVCount int) uint16 {
	var ctx uint16
	switch nearestMatch {
	case 0:
		if refMatchCount >= 1 {
			ctx |= 1
		}
		if refMatchCount == 1 {
			ctx |= 1 << refMVOffset
		} else if refMatchCount >= 2 {
			ctx |= 2 << refMVOffset
		}
	case 1:
		if newMVCount > 0 {
			ctx |= 2
		} else {
			ctx |= 3
		}
		if refMatchCount == 1 {
			ctx |= 3 << refMVOffset
		} else if refMatchCount >= 2 {
			ctx |= 4 << refMVOffset
		}
	default:
		if newMVCount >= 1 {
			ctx |= 4
		} else {
			ctx |= 5
		}
		ctx |= 5 << refMVOffset
	}
	return ctx
}

func sortReferenceMVStack(stack *ReferenceMVStack, start int, end int) {
	if start < 0 {
		start = 0
	}
	if end > stack.Count {
		end = stack.Count
	}
	for n := end; n > start; {
		next := start
		for i := start + 1; i < n; i++ {
			if stack.Candidates[i-1].Weight < stack.Candidates[i].Weight {
				stack.Candidates[i-1], stack.Candidates[i] = stack.Candidates[i], stack.Candidates[i-1]
				next = i
			}
		}
		n = next
	}
}

func (mode InterModeResult) usesNewMV() bool {
	if mode.Compound {
		return mode.CompoundMode == CompoundInterModeNewNew ||
			mode.CompoundMode == CompoundInterModeNearestNew ||
			mode.CompoundMode == CompoundInterModeNewNearest ||
			mode.CompoundMode == CompoundInterModeNearNew ||
			mode.CompoundMode == CompoundInterModeNewNear
	}
	return mode.Mode == InterModeNewMV
}

type compoundReferenceLists struct {
	id        [2][MaxMVRefCandidates]motion.Vector
	diff      [2][MaxMVRefCandidates]motion.Vector
	idCount   [2]int
	diffCount [2]int
}

func (lists *compoundReferenceLists) add(candidate InterMotionResult, target [2]ReferenceFrame, signBias [referenceFrameCount]bool) {
	for refIdx := 0; refIdx < 2; refIdx++ {
		candidateRef := candidate.References.Ref[refIdx]
		if !candidateRef.Valid() {
			continue
		}
		for cmpIdx := 0; cmpIdx < 2; cmpIdx++ {
			if candidateRef == target[cmpIdx] {
				if lists.idCount[cmpIdx] < MaxMVRefCandidates {
					lists.id[cmpIdx][lists.idCount[cmpIdx]] = candidate.MV[refIdx]
					lists.idCount[cmpIdx]++
				}
				continue
			}
			if lists.diffCount[cmpIdx] < MaxMVRefCandidates {
				mv := candidate.MV[refIdx]
				if signBias[candidateRef] != signBias[target[cmpIdx]] {
					mv = negateMV(mv)
				}
				lists.diff[cmpIdx][lists.diffCount[cmpIdx]] = mv
				lists.diffCount[cmpIdx]++
			}
		}
	}
}

func (lists *compoundReferenceLists) compoundList(req ReferenceMVStackRequest) [MaxMVRefCandidates][2]motion.Vector {
	var out [MaxMVRefCandidates][2]motion.Vector
	for refIdx := 0; refIdx < 2; refIdx++ {
		outIdx := 0
		for i := 0; i < lists.idCount[refIdx] && outIdx < MaxMVRefCandidates; i++ {
			out[outIdx][refIdx] = lists.id[refIdx][i]
			outIdx++
		}
		for i := 0; i < lists.diffCount[refIdx] && outIdx < MaxMVRefCandidates; i++ {
			out[outIdx][refIdx] = lists.diff[refIdx][i]
			outIdx++
		}
		for outIdx < MaxMVRefCandidates {
			out[outIdx][refIdx] = req.GlobalMVs[refIdx]
			outIdx++
		}
	}
	return out
}

func negateMV(v motion.Vector) motion.Vector {
	return motion.Vector{Row: -v.Row, Col: -v.Col}
}

func (stack ReferenceMVStack) validateCount(need int) error {
	if err := stack.validate(); err != nil {
		return err
	}
	if need < 0 || need > MaxRefMVStackSize || stack.Count < need {
		return ErrInvalidDecodeState
	}
	return nil
}
