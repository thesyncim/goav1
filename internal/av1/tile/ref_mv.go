var debugRefMV = os.Getenv("GOAV1_DEBUG_REFMV") != ""

func dbgPrintf(req ReferenceMVStackRequest, format string, args ...any) {
	if !debugRefMV {
		return
	}
	if req.MIRow != 34 || req.MICol != 4 {
		return
	}
	fmt.Fprintf(os.Stderr, "REFMV mi=(%d,%d) X4=%d Y4=%d size=%d: ", req.MICol, req.MIRow, req.X4, req.Y4, req.Size)
	fmt.Fprintf(os.Stderr, format, args...)
	fmt.Fprintln(os.Stderr)
}

const (
	MaxMVRefCandidates   = 2
	MaxRefMVStackSize    = 8
	UsableRefMVStackSize = 4
	RefMVCategoryLevel   = 640
)

// InterMotionResult is the decoded inter mode plus its final motion vectors.
type InterMotionResult struct {
	References InterReferencesResult
	Mode       InterModeResult
	MV         [2]motion.Vector
	InterIntra bool
}

// ReferenceMVCandidate mirrors libaom's CANDIDATE_MV/ref_mv_weight entry.
type ReferenceMVCandidate struct {
	This     motion.Vector
	Compound motion.Vector
	Weight   uint16
}

// ReferenceMVStack is the candidate stack generated by the reference-MV search.
type ReferenceMVStack struct {
	Candidates     [MaxRefMVStackSize]ReferenceMVCandidate
	Count          int
	SingleRefMVs   [MaxMVRefCandidates]motion.Vector
	SingleRefValid bool
}

// ReferenceMVStackRequest selects the spatial MV stack for one inter block.
type ReferenceMVStackRequest struct {
	Size       BlockSize
	References InterReferencesResult

	X4           int
	Y4           int
	HaveTop      bool
	HaveLeft     bool
	HaveTopRight bool

	MICol uint32
	MIRow uint32

	TileMIColStart uint32
	TileMIRowStart uint32
	TileMIColEnd   uint32
	TileMIRowEnd   uint32

	GlobalMVs        [2]motion.Vector
	GlobalMotionType [2]parser.GlobalMotionType
	RefSignBias      [referenceFrameCount]bool

	TemporalMVs          *TemporalMotionField
	OrderHintBits        uint8
	CurrentOrderHint     uint32
	ReferenceOrderHints  [referenceFrameCount]uint32
	AllowHighPrecisionMV bool
	ForceIntegerMV       bool

	UseRefFrameMVS              bool
	TemporalMVSampleUnavailable bool
}

type ReferenceMVStackResult struct {
	Stack         ReferenceMVStack
	ModeContext   uint16
	NearestCount  int
	RowMatches    int
	ColumnMatches int
	NewMVMatches  int
}

// IntrabcReferenceDVStack returns the spatial DV candidates used by intrabc's
// INTRA_FRAME mv-ref search. Intrabc stores decoded DVs in the same neighbor
// grids as inter motion, but without inter reference frames.
func (c *BlockModeContext) IntrabcReferenceDVStack(req ReferenceMVStackRequest) (ReferenceMVStack, error) {
	dims, err := validateIntrabcReferenceDVStackRequest(req)
	if err != nil {
		return ReferenceMVStack{}, err
	}
	searchMaxRowOffset, searchMaxColOffset, _, _ := referenceMVSearchOffsets(req, dims)
	processedRows := 0
	processedCols := 0
	var stack ReferenceMVStack
	if req.HaveTop && absInt(searchMaxRowOffset) >= 1 {
		c.scanAboveIntrabcDVs(req, dims, searchMaxRowOffset, &processedRows, &stack)
	}
	if req.HaveLeft && absInt(searchMaxColOffset) >= 1 {
		c.scanLeftIntrabcDVs(req, dims, searchMaxColOffset, &processedCols, &stack)
	}
	if req.HaveTopRight {
		if candidate, _, ok := c.topRightInterMotion(req, dims); ok {
			stack.addOrWeight(ReferenceMVCandidate{This: candidate.MV[0]}, 4)
		}
	}
	nearestCount := stack.Count
	for i := 0; i < nearestCount; i++ {
		stack.Candidates[i].Weight += RefMVCategoryLevel
	}
	// Pass the full tile-clamped offsets (not the in-SB grid-capped variants)
	// so cross-superblock outer scans reach into the prior SB's interior via
	// the SBTopInterMotionGrid / SBLeftInterMotionGrid snapshots, mirroring
	// libaom's frame-wide mi grid.
	c.scanOuterIntrabcDVs(req, dims, searchMaxRowOffset, searchMaxColOffset, processedRows, processedCols, &stack)
	sortReferenceMVStack(&stack, 0, nearestCount)
	sortReferenceMVStack(&stack, nearestCount, stack.Count)
	return stack, nil
}

// InterMVReferenceSet contains the stack-derived MV bases needed before MV
// residual syntax is applied.
type InterMVReferenceSet struct {
	Nearest  [2]motion.Vector
	Near     [2]motion.Vector
	Residual [2]motion.Vector
}

// DRLContext returns libaom's av1_drl_ctx()/dav1d's get_drl_context() value.
func (stack ReferenceMVStack) DRLContext(refIdx int) (int, error) {
	if err := stack.validate(); err != nil {
		return 0, err
	}
	if refIdx < 0 || refIdx+1 >= stack.Count {
		return 0, ErrInvalidDecodeState
	}
	cur := stack.Candidates[refIdx].Weight >= RefMVCategoryLevel
	next := stack.Candidates[refIdx+1].Weight >= RefMVCategoryLevel
	switch {
	case cur && next:
		return 0, nil
	case cur && !next:
		return 1, nil
	case !cur && !next:
		return 2, nil
	default:
		return 0, nil
	}
}

// DRLContexts returns the three contexts read_drl_idx may consult.
func (stack ReferenceMVStack) DRLContexts() ([3]int, error) {
	var contexts [3]int
	if err := stack.validate(); err != nil {
		return contexts, err
	}
	for i := range contexts {
		if i+1 >= stack.Count {
			break
		}
		ctx, err := stack.DRLContext(i)
		if err != nil {
			return contexts, err
		}
		contexts[i] = ctx
	}
	return contexts, nil
}

// DRLRequestForMode builds the DRL syntax request for a decoded inter mode.
func (stack ReferenceMVStack) DRLRequestForMode(mode InterModeResult) (DRLRequest, error) {
	if mode.Compound {
		if !mode.CompoundMode.Valid() {
			return DRLRequest{}, ErrInvalidDecodeState
		}
	} else if !mode.Mode.Valid() {
		return DRLRequest{}, ErrInvalidDecodeState
	}
	contexts, err := stack.DRLContexts()
	if err != nil {
		return DRLRequest{}, err
	}
	return DRLRequest{
		Mode:         mode.Mode,
		CompoundMode: mode.CompoundMode,
		Compound:     mode.Compound,
		RefMVCount:   stack.Count,
		Contexts:     contexts,
	}, nil
}

// BestSingleReferenceMVs returns av1_find_best_ref_mvs()'s nearest/near pair.
func (stack ReferenceMVStack) BestSingleReferenceMVs(allowHighPrecision bool, forceInteger bool) (motion.Vector, motion.Vector, error) {
	if stack.SingleRefValid {
		nearest := motion.LowerPrecision(stack.SingleRefMVs[0], allowHighPrecision, forceInteger)
		near := motion.LowerPrecision(stack.SingleRefMVs[1], allowHighPrecision, forceInteger)
		return nearest, near, nil
	}
	if err := stack.validateCount(MaxMVRefCandidates); err != nil {
		return motion.Vector{}, motion.Vector{}, err
	}
	nearest := motion.LowerPrecision(stack.Candidates[0].This, allowHighPrecision, forceInteger)
	near := motion.LowerPrecision(stack.Candidates[1].This, allowHighPrecision, forceInteger)
	return nearest, near, nil
}

// ResolveInterMVReferences ports the stack-selection part of libaom's
// read_inter_block_mode_info()/assign_mv() path before MV residual bits.
func (stack ReferenceMVStack) ResolveInterMVReferences(mode InterModeResult, refMVIndex int, allowHighPrecision bool, forceInteger bool) (InterMVReferenceSet, error) {
	if err := stack.validate(); err != nil {
		return InterMVReferenceSet{}, err
	}
	if refMVIndex < 0 || refMVIndex >= UsableRefMVStackSize {
		return InterMVReferenceSet{}, ErrInvalidDecodeState
	}
	if mode.Compound {
		return stack.resolveCompoundInterMVReferences(mode.CompoundMode, refMVIndex, allowHighPrecision, forceInteger)
	}
	return stack.resolveSingleInterMVReferences(mode.Mode, refMVIndex, allowHighPrecision, forceInteger)
}

func (stack ReferenceMVStack) resolveSingleInterMVReferences(mode InterMode, refMVIndex int, allowHighPrecision bool, forceInteger bool) (InterMVReferenceSet, error) {
	if !mode.Valid() || mode == InterModeGlobalMV {
		return InterMVReferenceSet{}, ErrInvalidDecodeState
	}
	nearest, near, err := stack.BestSingleReferenceMVs(allowHighPrecision, forceInteger)
	if err != nil {
		return InterMVReferenceSet{}, err
	}
	if mode == InterModeNearMV && refMVIndex > 0 {
		candidate, err := stack.candidate(1 + refMVIndex)
		if err != nil {
			return InterMVReferenceSet{}, err
		}
		near = candidate.This
	}
	refs := InterMVReferenceSet{
		Nearest:  [2]motion.Vector{nearest},
		Near:     [2]motion.Vector{near},
		Residual: [2]motion.Vector{nearest},
	}
	if mode == InterModeNewMV && stack.Count > 1 {
		candidate, err := stack.candidate(refMVIndex)
		if err != nil {
			return InterMVReferenceSet{}, err
		}
		refs.Residual[0] = candidate.This
	}
	return refs, nil
}

func (stack ReferenceMVStack) resolveCompoundInterMVReferences(mode CompoundInterMode, refMVIndex int, allowHighPrecision bool, forceInteger bool) (InterMVReferenceSet, error) {
	if !mode.Valid() || mode == CompoundInterModeGlobalGlobal {
		return InterMVReferenceSet{}, ErrInvalidDecodeState
	}
	nearestCandidate, err := stack.candidate(0)
	if err != nil {
		return InterMVReferenceSet{}, err
	}
	refs := InterMVReferenceSet{
		Nearest: [2]motion.Vector{
			motion.LowerPrecision(nearestCandidate.This, allowHighPrecision, forceInteger),
			motion.LowerPrecision(nearestCandidate.Compound, allowHighPrecision, forceInteger),
		},
	}
	refs.Near = refs.Nearest
	if mode == CompoundInterModeNearNear || mode == CompoundInterModeNearNew || mode == CompoundInterModeNewNear {
		nearCandidate, err := stack.candidate(1 + refMVIndex)
		if err != nil {
			return InterMVReferenceSet{}, err
		}
		refs.Near = [2]motion.Vector{
			motion.LowerPrecision(nearCandidate.This, allowHighPrecision, forceInteger),
			motion.LowerPrecision(nearCandidate.Compound, allowHighPrecision, forceInteger),
		}
	}
	refs.Residual = refs.Nearest

	components, err := mode.Components()
	if err != nil {
		return InterMVReferenceSet{}, err
	}
	residualIndex := refMVIndex
	if mode == CompoundInterModeNearNew || mode == CompoundInterModeNewNear {
		residualIndex = 1 + refMVIndex
	}
	residualCandidate, err := stack.candidate(residualIndex)
	if err != nil {
		return InterMVReferenceSet{}, err
	}
	if components.First == InterModeNewMV {
		refs.Residual[0] = residualCandidate.This
	}
	if components.Second == InterModeNewMV {
		refs.Residual[1] = residualCandidate.Compound
	}
	return refs, nil
}

func (stack ReferenceMVStack) candidate(index int) (ReferenceMVCandidate, error) {
	if err := stack.validate(); err != nil {
		return ReferenceMVCandidate{}, err
	}
	if index < 0 || index >= stack.Count {
		return ReferenceMVCandidate{}, ErrInvalidDecodeState
	}
	return stack.Candidates[index], nil
}

func (stack ReferenceMVStack) validate() error {
	if stack.Count < 0 || stack.Count > MaxRefMVStackSize {
		return ErrInvalidDecodeState
	}
	return nil
}

// MarkInterMotion updates the top/left context once a block's inter MVs are known.
func (c *BlockModeContext) MarkInterMotion(size BlockSize, x4 int, y4 int, result InterMotionResult) error {
	if err := validateInterMotion(result); err != nil {
		return err
	}
	if err := c.MarkInter(size, x4, y4, result.References); err != nil {
		return err
	}
	dims, ok := size.Dimensions()
	if !ok {
		return ErrInvalidDecodeState
	}
	for i := 0; i < int(dims.W4); i++ {
		c.AboveInterMotion[x4+i] = result
		c.AboveMotionValid[x4+i] = 1
		c.AboveBlockSize[x4+i] = size
	}
	for i := 0; i < int(dims.H4); i++ {
		c.LeftInterMotion[y4+i] = result
		c.LeftMotionValid[y4+i] = 1
		c.LeftBlockSize[y4+i] = size
	}
	c.markGridInterMotion(size, x4, y4, result, dims)
	return nil
}

// MarkIntrabcMotion updates top/left motion context for intra-block-copy DVs.
func (c *BlockModeContext) MarkIntrabcMotion(size BlockSize, x4 int, y4 int, result InterMotionResult) error {
	if c == nil || !result.Mode.Mode.Valid() {
		return ErrInvalidDecodeState
	}
	dims, ok := size.Dimensions()
	if !ok || x4 < 0 || y4 < 0 ||
		x4+int(dims.W4) > MaxBlockModeSlots ||
		y4+int(dims.H4) > MaxBlockModeSlots {
		return ErrInvalidDecodeState
	}
	for i := 0; i < int(dims.W4); i++ {
		c.AboveIntra[x4+i] = 0
		c.AboveMode[x4+i] = IntraModeDC
		c.AboveChromaIntra[x4+i] = 0
		c.AboveChromaMode[x4+i] = ChromaIntraModeDC
		c.AboveRef[0][x4+i] = ReferenceFrameNone
		c.AboveRef[1][x4+i] = ReferenceFrameNone
		c.AboveCompound[x4+i] = 0
		c.AboveInterMotion[x4+i] = result
		c.AboveMotionValid[x4+i] = 1
		c.AboveInterp[x4+i] = motion.InterpFilters{}
		c.AboveInterpValid[x4+i] = 0
		c.AboveBlockSize[x4+i] = size
		c.AbovePaletteY[x4+i] = paletteContext{}
		c.AbovePaletteUV[x4+i] = paletteContext{}
	}
	for i := 0; i < int(dims.H4); i++ {
		c.LeftIntra[y4+i] = 0
		c.LeftMode[y4+i] = IntraModeDC
		c.LeftChromaIntra[y4+i] = 0
		c.LeftChromaMode[y4+i] = ChromaIntraModeDC
		c.LeftRef[0][y4+i] = ReferenceFrameNone
		c.LeftRef[1][y4+i] = ReferenceFrameNone
		c.LeftCompound[y4+i] = 0
		c.LeftInterMotion[y4+i] = result
		c.LeftMotionValid[y4+i] = 1
		c.LeftInterp[y4+i] = motion.InterpFilters{}
		c.LeftInterpValid[y4+i] = 0
		c.LeftBlockSize[y4+i] = size
		c.LeftPaletteY[y4+i] = paletteContext{}
		c.LeftPaletteUV[y4+i] = paletteContext{}
	}
	c.markGridInterMotion(size, x4, y4, result, dims)
	return nil
}

func (c *BlockModeContext) markGridInterMotion(size BlockSize, x4 int, y4 int, result InterMotionResult, dims BlockDimensions) {
	for y := y4; y < y4+int(dims.H4); y++ {
		if y < 0 || y >= MaxBlockModeSlots {
			continue
		}
		for x := x4; x < x4+int(dims.W4); x++ {
			if x < 0 || x >= MaxBlockModeSlots {
				continue
			}
			c.GridInterMotion[y][x] = result
			c.GridMotionValid[y][x] = 1
			c.GridBlockSize[y][x] = size
			c.GridBlockSizeVisited[y][x] = 1
		}
	}
}

// clearGridInterMotion marks the block's grid cells as having no motion
// candidate (MotionValid=0) while preserving the block size so outer ref-MV
// scans can still advance by the candidate's mi_size step. libaom's
// scan_row_mbmi / scan_col_mbmi advance i += len = AOMMIN(xd->size,
// mi_size_*[candidate->bsize]) regardless of whether the candidate is inter
// or intra, so an intra neighbor consumes its full extent in the scan and
// blocks deeper in the column/row are skipped. Zeroing GridBlockSize would
// collapse the step to 1 (4x4) and let goav1's outer scan oversample cells
// libaom never visits, producing a spurious column/row match.
func (c *BlockModeContext) clearGridInterMotion(size BlockSize, x4 int, y4 int, dims BlockDimensions) {
	for y := y4; y < y4+int(dims.H4); y++ {
		if y < 0 || y >= MaxBlockModeSlots {
			continue
		}
		for x := x4; x < x4+int(dims.W4); x++ {
			if x < 0 || x >= MaxBlockModeSlots {
				continue
			}
			c.GridInterMotion[y][x] = InterMotionResult{}
			c.GridMotionValid[y][x] = 0
			c.GridBlockSize[y][x] = size
			c.GridBlockSizeVisited[y][x] = 1
		}
	}
}

// BuildReferenceMVStack ports the spatial part of libaom's setup_ref_mv_list()
// for the immediate above row and left column tracked by BlockModeContext.
func (c *BlockModeContext) BuildReferenceMVStack(req ReferenceMVStackRequest) (ReferenceMVStackResult, error) {
	if c == nil {
		return ReferenceMVStackResult{}, ErrInvalidDecodeState
	}
	dims, err := validateReferenceMVStackRequest(req)
	if err != nil {
		return ReferenceMVStackResult{}, err
	}

	searchMaxRowOffset, searchMaxColOffset, gridMaxRowOffset, gridMaxColOffset := referenceMVSearchOffsets(req, dims)
	processedRows := 0
	processedCols := 0
	var result ReferenceMVStackResult
	if req.HaveTop && absInt(searchMaxRowOffset) >= 1 {
		c.scanAboveReferenceMVs(req, dims, searchMaxRowOffset, &processedRows, &result)
	}
	if req.HaveLeft && absInt(searchMaxColOffset) >= 1 {
		c.scanLeftReferenceMVs(req, dims, searchMaxColOffset, &processedCols, &result)
	}
	if req.HaveTopRight {
		c.scanTopRightReferenceMV(req, dims, &result)
	}
	nearestMatch := boolInt(result.RowMatches > 0) + boolInt(result.ColumnMatches > 0)
	result.NearestCount = result.Stack.Count
	for i := 0; i < result.NearestCount; i++ {
		result.Stack.Candidates[i].Weight += RefMVCategoryLevel
	}
	modeContextFlags := uint16(0)
	temporalUnavailable := req.TemporalMVSampleUnavailable
	if req.UseRefFrameMVS && req.TemporalMVs != nil {
		temporal, err := req.temporalReferenceMVs(dims, &result.Stack)
		if err != nil {
			return ReferenceMVStackResult{}, err
		}
		temporalUnavailable = !temporal.FirstAvailable
		if temporal.GlobalMVDifferent {
			modeContextFlags |= 1 << globalMVOffset
		}
	}
	if req.UseRefFrameMVS && temporalUnavailable {
		modeContextFlags |= 1 << globalMVOffset
	}
	c.scanOuterReferenceMVs(req, dims, gridMaxRowOffset, gridMaxColOffset, processedRows, processedCols, &result)
	refMatchCount := boolInt(result.RowMatches > 0) + boolInt(result.ColumnMatches > 0)
	result.ModeContext = referenceMVModeContext(nearestMatch, refMatchCount, result.NewMVMatches) | modeContextFlags
	sortReferenceMVStack(&result.Stack, 0, result.NearestCount)

	if req.References.Compound {
		c.extendCompoundReferenceMVStack(req, dims, &result.Stack)
	} else {
		c.extendSingleReferenceMVStack(req, dims, &result.Stack)
	}
	sortReferenceMVStack(&result.Stack, result.NearestCount, result.Stack.Count)
	if !req.References.Compound {
		// Refresh the single-ref MV cache from the post-sort stack so
		// NEARESTMV/NEARMV decoders read the highest-weighted slot.
		// libaom's av1_setup_ref_mv_list populates mv_ref_list FROM the
		// sorted ref_mv_stack; priming SingleRefMVs inside
		// extendSingleReferenceMVStack let insertion order leak into the
		// nearest/near cache, e.g. quantizer_00 frame 1 mi=(46,10).
		result.Stack.setSingleRefMVs(req.GlobalMVs[0])
	}
	dbgPrintf(req, "STACK count=%d row=%d col=%d ctx=%d nearest=%d", result.Stack.Count, result.RowMatches, result.ColumnMatches, result.ModeContext, result.NearestCount)
	for i := 0; i < result.Stack.Count; i++ {
		dbgPrintf(req, "  stack[%d] this=(%d,%d) w=%d", i, result.Stack.Candidates[i].This.Row, result.Stack.Candidates[i].This.Col, result.Stack.Candidates[i].Weight)
	}
	return result, nil
}

const (
	refMVRowCols       = 3
	refMVMaxScanBlock4 = 16
)

type temporalReferenceMVResult struct {
	FirstAvailable    bool
	GlobalMVDifferent bool
}

func (req ReferenceMVStackRequest) temporalReferenceMVs(dims BlockDimensions, stack *ReferenceMVStack) (temporalReferenceMVResult, error) {
	if req.TemporalMVs == nil {
		return temporalReferenceMVResult{}, nil
	}
	if err := req.TemporalMVs.validate(); err != nil {
		return temporalReferenceMVResult{}, err
	}
	voffset := maxInt(2, int(dims.H4))
	hoffset := maxInt(2, int(dims.W4))
	blkRowEnd := minInt(int(dims.H4), 16)
	blkColEnd := minInt(int(dims.W4), 16)
	stepH := 2
	if dims.H4 >= 16 {
		stepH = 4
	}
	stepW := 2
	if dims.W4 >= 16 {
		stepW = 4
	}

	var result temporalReferenceMVResult
	for blkRow := 0; blkRow < blkRowEnd; blkRow += stepH {
		for blkCol := 0; blkCol < blkColEnd; blkCol += stepW {
			added, different, err := req.addTemporalReferenceMV(blkRow, blkCol, stack)
			if err != nil {
				return temporalReferenceMVResult{}, err
			}
			if blkRow == 0 && blkCol == 0 {
				result.FirstAvailable = added
				// libaom only sets the GLOBALMV mode-context bit based on the
				// (blk_row=0, blk_col=0) temporal sample. Earlier goav1 OR'd
				// `different` across the whole scan and the extension
				// positions, which produced a different mode_context whenever
				// a non-(0,0) temporal MV deviated from the global MV by 16+
				// quarter pels and incorrectly steered inter mode reads to
				// zeromv_cdf[1] instead of zeromv_cdf[0] for blocks with no
				// (0,0) temporal sample available.
				if different {
					result.GlobalMVDifferent = true
				}
			}
		}
	}

	allowExtension := dims.H4 >= 2 && dims.H4 < 16 && dims.W4 >= 2 && dims.W4 < 16
	if allowExtension {
		positions := [3][2]int{
			{voffset, -2},
			{voffset, hoffset},
			{voffset - 2, hoffset},
		}
		for _, pos := range positions {
			if _, _, err := req.addTemporalReferenceMV(pos[0], pos[1], stack); err != nil {
				return temporalReferenceMVResult{}, err
			}
		}
	}
	return result, nil
}

func (req ReferenceMVStackRequest) addTemporalReferenceMV(blkRow int, blkCol int, stack *ReferenceMVStack) (bool, bool, error) {
	rowOffset := blkRow
	if req.MIRow&1 == 0 {
		rowOffset++
	}
	colOffset := blkCol
	if req.MICol&1 == 0 {
		colOffset++
	}
	absRow := int64(req.MIRow) + int64(rowOffset)
	absCol := int64(req.MICol) + int64(colOffset)
	if absRow < int64(req.TileMIRowStart) || absRow >= int64(req.TileMIRowEnd) ||
		absCol < int64(req.TileMIColStart) || absCol >= int64(req.TileMIColEnd) {
		return false, false, nil
	}
	sampleRow := int(absRow >> 1)
	sampleCol := int(absCol >> 1)
	if sampleRow < 0 || sampleRow >= req.TemporalMVs.Rows ||
		sampleCol < 0 || sampleCol >= req.TemporalMVs.Cols {
		return false, false, nil
	}
	sample := req.TemporalMVs.Entries[sampleRow*req.TemporalMVs.Stride+sampleCol]
	if !sample.Valid {
		return false, false, nil
	}

	first, err := req.temporalProjectedMV(sample, 0)
	if err != nil {
		return false, false, err
	}
	different := temporalMVDifferent(first, req.GlobalMVs[0])
	candidate := ReferenceMVCandidate{This: first}
	if req.References.Compound {
		second, err := req.temporalProjectedMV(sample, 1)
		if err != nil {
			return false, false, err
		}
		candidate.Compound = second
		different = different || temporalMVDifferent(second, req.GlobalMVs[1])
	}
	stack.addOrWeight(candidate, 2)
	return true, different, nil
}

func (req ReferenceMVStackRequest) temporalProjectedMV(sample TemporalMotionEntry, refIndex int) (motion.Vector, error) {
	ref := req.References.Ref[refIndex]
	if !ref.Valid() {
		return motion.Vector{}, ErrInvalidDecodeState
	}
	currentOffset, err := motionFieldRelativeOrderHint(req.OrderHintBits, req.CurrentOrderHint, req.ReferenceOrderHints[ref])
	if err != nil {
		return motion.Vector{}, err
	}
	projected, err := motionFieldProjectMV(sample.MV, currentOffset, sample.RefFrameOffset)
	if err != nil {
		return motion.Vector{}, err
	}
	return motion.LowerPrecision(projected, req.AllowHighPrecisionMV, req.ForceIntegerMV), nil
}

func temporalMVDifferent(a motion.Vector, b motion.Vector) bool {
	return absInt32(a.Row-b.Row) >= 16 || absInt32(a.Col-b.Col) >= 16
}

func absInt32(v int32) int32 {
	if v < 0 {
		return -v
	}
	return v
}

func (c *BlockModeContext) scanAboveReferenceMVs(req ReferenceMVStackRequest, dims BlockDimensions, maxRowOffset int, processedRows *int, result *ReferenceMVStackResult) {
	end := minInt(int(dims.W4), MaxBlockModeSlots-req.X4)
	end = minInt(end, refMVMaxScanBlock4)
	for off := 0; off < end; {
		slot := req.X4 + off
		size := c.AboveBlockSize[slot]
		sizeW4 := blockSizeWidth4(size)
		sizeH4 := blockSizeHeight4(size)
		// libaom's scan_row_mbmi sets the iteration stride and
		// processed_rows from the neighbor's block size regardless of
		// whether the neighbor is inter or intra. Gating these updates on
		// AboveMotionValid kept processedRows at zero when the nearest above
		// row was intra, which let the outer scan re-enter row offsets
		// libaom already covered and prematurely promote processedRows on a
		// duplicate candidate, hiding the row=-5 outer sample that libaom
		// adds to the ref-MV stack.
		step := minInt(int(dims.W4), sizeW4)
		if dims.W4 >= refMVMaxScanBlock4 {
			step = maxInt(step, 4)
		}
		if step > end-off {
			step = end - off
		}
		if step <= 0 {
			step = 1
		}
		weight := 2
		if dims.W4 >= 2 && int(dims.W4) <= sizeW4 {
			inc := minInt(-maxRowOffset, sizeH4)
			weight = maxInt(weight, inc)
			*processedRows = inc
		}
		if c.AboveIntra[slot] == 0 && c.AboveMotionValid[slot] != 0 {
			matches, newMatches := result.Stack.addDirectCandidate(c.AboveInterMotion[slot], c.AboveBlockSize[slot], req.References, uint16(step*weight), req.GlobalMVs, req.GlobalMotionType)
			result.RowMatches += matches
			result.NewMVMatches += newMatches
		}
		off += step
	}
}

