// NEON-accelerated inverse DCT64 four-column kernel.
//
// Four adjacent columns of the row-major scratch buffer ride the four int32
// lanes of each .4s register, following dav1d's high-bitdepth inverse
// transform shape (dav1d src/arm/64/itx16.S: inv_dct64_step1_neon /
// inv_dct64_step2_neon and the mul_mla/mul_mls + srshr + smax/smin idiom):
// every butterfly multiply is a plain mul/mla/mls .4s, every rounding shift
// is srshr .4s and every stage clamp is smax+smin against the stage bounds.
// Working in int32 lanes without widening is exact because the column-pass
// inputs are pre-clamped to the stage range (|v| <= 2^19 across all supported
// bit depths) and every cosine pair, after rewriting coefficients with
// |w| > 2048 as w-4096 plus a compensating post-shift add of the (clamped)
// input -- an exact integer identity at cos_bit=12 -- keeps the multiply
// accumulator below 2^31. The adapter enforces the clamp-bound precondition
// and falls back to pure Go otherwise.
//
// Like dav1d's dct64 (which also works through a stack buffer), the 64-entry
// stage buffer lives in caller-provided scratch memory and each stage runs as
// independent two-slot butterfly groups, so the kernel's own frame is only
// 528 bytes -- inside the nosplit stack budget. (The earlier, unbound DCT64
// column kernel kept the whole transform in a 2048-byte manual frame below a
// NOSPLIT $0 Go frame, overflowing the nosplit headroom guarantee and
// corrupting adjacent memory on shallow goroutine stacks; this kernel
// replaces it.)
//
// The body is generated by transliterating the pure-Go inverseDCT64 butterfly
// to NEON intrinsics, compiling with the system C compiler at -O2 and
// transcribing the disassembly verbatim as WORD-encoded opcodes, because Go's
// arm64 assembler does not expose the signed-rounding-shift mnemonics. The
// kernel is pure straight-line leaf code (no branches, no calls) and restores
// every callee-saved register before returning. It is bit-for-bit identical
// to running the pure-Go inverseDCT64 on each column, asserted exhaustively
// by the column dispatch differential tests.
//
