// fwdRoundShift2V is fwdRoundShift2 per lane: (v + 2) >> 2 (16x16 shift[1]).
func fwdRoundShift2V(v fwdVec) fwdVec {
	return fwdShr(v.Add(fwdConst2), 2)
}

// fwdRoundShift4V is fwdRoundShift4 per lane: (v + 8) >> 4 (32x32 shift[1]).
func fwdRoundShift4V(v fwdVec) fwdVec {
	return fwdShr(v.Add(fwdConst8), 4)
}

// forwardDCT16x16SIMD is the 16x16 DCT_DCT kernel (forwardDCT16x16PureGo).
// The column pass stores its rows transposed, so coeff[c*16+k] holds
// column-pass row k of column c, and the row pass then transforms each group
// of four rows in place.
func forwardDCT16x16SIMD(coeff []int32, coeffStride int, residual []int16, residualStride int) {
	if coeffStride == 16 {
		forwardDCT16x16InPlace((*[256]int32)(coeff), residual, residualStride)
		return
	}
	var buf [256]int32
	forwardDCT16x16InPlace(&buf, residual, residualStride)
	for k := range 16 {
		copy(coeff[k*coeffStride:k*coeffStride+16], buf[k*16:])
	}
}

func forwardDCT16x16InPlace(c *[256]int32, residual []int16, residualStride int) {
	for g := 0; g < 16; g += fwdLanes {
		fwdColDCT16(c[:], g, residual, residualStride)
	}
	for h := 0; h < 16; h += fwdLanes {
		fwdRowDCT16(c[:], h)
	}
}

// forwardDCT16x16SIMDGuarded routes residuals outside the 8-bit range to the
// int64 scalar reference.
func forwardDCT16x16SIMDGuarded(coeff []int32, coeffStride int, residual []int16, residualStride int) {
	if !residualFitsMagnitude(residual, residualStride, 16, 16, 255) {
		forwardDCT16x16PureGo(coeff, coeffStride, residual, residualStride)
		return
	}
	forwardDCT16x16SIMD(coeff, coeffStride, residual, residualStride)
}

// forwardDCT32x32SIMD is the 32x32 DCT_DCT kernel (forwardDCT32x32PureGo),
