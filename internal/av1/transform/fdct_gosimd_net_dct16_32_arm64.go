// Straight-line Go SIMD transcriptions of the 16- and 32-point forward DCT
// butterfly networks (fwdDCT16 and fwdDCT32 in fdct.go). Each statement
// reproduces the scalar statement at the same position, so the networks match
// the scalar oracle exactly. The int32 lanes are exact over the 8-bit residual
// guard: every half-butterfly pre-shift sum is bounded below 2^31 there.
//
// The arm64 forms load their twiddles off one table pointer and spell each
// butterfly out as intrinsics, so every operand is a single load at a constant
// offset and no inline-mark NOPs separate the operations; the amd64 forms keep
// the broadcast constants (fdct_gosimd_net_dct16_32_amd64.go).

// fwdTw12 is the cos_bit 12 twiddle table of the 16- and 32-point networks.
var fwdTw12 = newFwd64Twiddles(&fwdCospi12, 12)

