// NEON-accelerated inverse DCT32 row and column kernels.
//
// Two independent 32-point inverse DCTs run at once, one in lane 0 and one in
// lane 1 of each 64-bit-element NEON register. The row kernel takes two
// adjacent stride-1 rows and interleaves them with ZIP so coefficient index i
// of each row shares a register; the column kernel takes two adjacent columns
// of the row-major scratch buffer, which already sit in lanes 0/1 of a strided
// .2s load. Every multiply widens int32->int64 (SMULL/SMLAL), every rounding
// shift is SRSHR and every stage clamp is the CMGT+BSL (BIT/BIF) select, so the
// fixed-point arithmetic, rounding and clamp ranges are bit-for-bit identical
// to the pure-Go inverseDCT32 / inverseDCT32Row references for every supported
// bit depth (8/10/12). This is asserted exhaustively by the row/column
// dispatch differential tests.
//
// The bodies are generated by compiling the equivalent NEON intrinsics
// (a line-by-line transliteration of the pure-Go butterfly) with the system C
// compiler at -O2 and transcribing the disassembly verbatim as WORD-encoded
// opcodes, because Go's arm64 assembler does not expose the signed
// widening-multiply and signed-rounding-shift mnemonics. The kernels are pure
// straight-line leaf code (no branches, no calls); they manage their own
// caller/callee-saved register spill frame below the (empty) Go frame and
// restore every callee-saved register before returning.
//
// SPDX-License-Identifier: BSD-2-Clause
//
