// NEON-accelerated inverse ADST16 four-row kernel.
//
// The row pass runs the horizontal 1D transform along stride-1 rows. This
// kernel transposes four adjacent 4x4 sub-blocks so four rows ride the four
// int32 lanes of each .4s register, runs the identical int32-lane ADST16
// butterfly used by the four-column kernel, then transposes back. Working in
// int32 lanes without widening is exact because the staged row inputs are
// pre-clamped to the stage range (|v| <= 2^19) and the |w| > 2048 coefficients
// (2751, 2276) are rewritten as w-4096 plus a compensating post-shift add of
// the clamped input (exact integer identity, accumulator < 2^31). The result
// is bit-for-bit identical to running the pure-Go inverseADST16 on each of the
// four rows, asserted by the row dispatch differential tests.
//
// Generated by transliterating the pure-Go butterfly (tools/itxgen:
// inverseADST16Core) to NEON intrinsics, compiling at -O2 and transcribing the
// disassembly verbatim as WORD-encoded opcodes (Go's arm64 assembler lacks the
// signed-rounding-shift mnemonics). Straight-line leaf code with a small spill
// frame within the nosplit budget.
//
