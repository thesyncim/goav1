// NEON-accelerated inverse DCT64 four-row kernel.
//
// Four adjacent stride-1 rows are transposed in 4x4 blocks (st4/ld4 through a
// caller-provided element-major buffer) so coefficient index i of the four
// rows shares the four int32 lanes of one .4s register, then the same
// int32-lane stage-buffer butterfly as the four-column DCT64 kernel runs:
// dav1d's high-bitdepth inverse transform shape (dav1d src/arm/64/itx16.S:
// inv_dct64_step1_neon / inv_dct64_step2_neon), with mul/mla/mls .4s
// multiplies, srshr rounding and smax+smin stage clamps. Working in int32
// lanes without widening is exact because the row-pass inputs are pre-clamped
// to the stage range (|v| <= 2^19 across all supported bit depths) and the
// (cospi-4096)-rewritten butterflies keep the multiply accumulator below
// 2^31; the adapter enforces the clamp-bound precondition and falls back
// otherwise. Bit-for-bit identical to inverseDCT64Row run on each row
// (asserted by the row dispatch differential tests).
//
// Like the four-column DCT64 kernel, the transpose buffer and 64-entry stage
// buffer live in caller-provided scratch (512 int32), keeping the kernel's
// own frame at 32 bytes -- well inside the nosplit stack budget (unlike the
// old, unbound two-row DCT64 kernel whose ~1.7KB manual NOSPLIT frame could
// corrupt shallow goroutine stacks).
//
// The body is generated by transliterating the pure-Go inverseDCT64 butterfly
// to NEON intrinsics, compiling with the system C compiler at -O2 and
// transcribing the disassembly verbatim as WORD-encoded opcodes. Pure
// straight-line leaf code; every callee-saved register is restored before
// returning.
//
// SPDX-License-Identifier: BSD-2-Clause
//
// See LICENSE for the BSD-2-Clause grant and NOTICE for the AOM attribution.

