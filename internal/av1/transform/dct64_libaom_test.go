	bf1[44] = clamp(-bf0[44] + bf0[47])
	bf1[45] = clamp(-bf0[45] + bf0[46])
	bf1[46] = clamp(bf0[45] + bf0[46])
	bf1[47] = clamp(bf0[44] + bf0[47])
	bf1[48] = clamp(bf0[48] + bf0[51])
	bf1[49] = clamp(bf0[49] + bf0[50])
	bf1[50] = clamp(bf0[49] - bf0[50])
