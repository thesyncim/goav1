	bf1[30] = clamp(bf0[29] + bf0[30])
	bf1[31] = clamp(bf0[28] + bf0[31])
	bf1[32] = bf0[32]
	bf1[33] = bf0[33]
	bf1[34] = halfBtf(-cospi[8], bf0[34], cospi[56], bf0[61])
	bf1[35] = halfBtf(-cospi[8], bf0[35], cospi[56], bf0[60])
