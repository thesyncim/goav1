	bf1[62] = clamp(-bf0[62] + bf0[63])
	bf1[63] = clamp(bf0[62] + bf0[63])

	// stage 4
	bf0 = output
	bf1 = step[:]
	for i := range 8 {
		bf1[i] = bf0[i]
	}
	bf1[8] = halfBtf(cospi[60], bf0[8], -cospi[4], bf0[15])
	bf1[9] = halfBtf(cospi[28], bf0[9], -cospi[36], bf0[14])
	bf1[10] = halfBtf(cospi[44], bf0[10], -cospi[20], bf0[13])
