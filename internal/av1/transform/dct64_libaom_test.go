	bf1[45] = halfBtf(cospi[19], bf0[45], -cospi[45], bf0[50])
	bf1[46] = halfBtf(cospi[35], bf0[46], -cospi[29], bf0[49])
	bf1[47] = halfBtf(cospi[3], bf0[47], -cospi[61], bf0[48])
