	bf1[24] = clamp(bf0[24] + bf0[27])
	bf1[25] = clamp(bf0[25] + bf0[26])
	bf1[26] = clamp(bf0[25] - bf0[26])
	bf1[27] = clamp(bf0[24] - bf0[27])
	bf1[28] = clamp(-bf0[28] + bf0[31])
